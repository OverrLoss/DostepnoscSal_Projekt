/// Parser ścieżek SVG obsługujący tylko M/L/Z (tyle jest w pliku).
Path floor1Path(String d) {
  final path = Path();
  final nums = <double>[];
  String cmd = 'M';
  void flush() {
    for (var i = 0; i + 1 < nums.length; i += 2) {
      final p = floor1ToCanvas(nums[i], nums[i + 1]);
      if (cmd == 'M' && i == 0) {
        path.moveTo(p.dx, p.dy);
      } else {
        path.lineTo(p.dx, p.dy);
      }
    }
    nums.clear();
  }

  for (final m in RegExp(r'([MLZ])|(-?\d+\.?\d*)').allMatches(d)) {
    if (m.group(1) != null) {
      flush();
      cmd = m.group(1)!;
      if (cmd == 'Z') path.close();
    } else {
      nums.add(double.parse(m.group(2)!));
    }
  }
  flush();
  return path;
}

